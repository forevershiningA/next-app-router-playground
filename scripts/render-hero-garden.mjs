import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ffmpeg from 'ffmpeg-static';
import sharp from 'sharp';

// Offline concept render: generated garden still + actual configurator footage.
// No generated interface or live WebGL is shipped to homepage visitors.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'public/videos');
const matchedSource = path.join(root, 'assets/video-sources/hero-garden-v2');
const duration = 12;
const fps = 25;
const matched = process.argv.includes('--matched');
const name = matched ? 'hero-garden-v2' : 'hero-garden-v1';
await mkdir(output, { recursive: true });
if (matched) {
  // The background stays an illustration; the headstone itself is the exact
  // renderer output used in all laptop frames, never regenerated by AI.
  const shadow = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="1672" height="941"><defs><filter id="blur"><feGaussianBlur stdDeviation="20"/></filter></defs><ellipse cx="1282" cy="766" rx="310" ry="33" fill="#0b140d" opacity=".55" filter="url(#blur)"/></svg>`,
  );
  await sharp(path.join(matchedSource, 'garden-plate.webp'))
    .composite([{ input: shadow }])
    .webp({ quality: 94 })
    .toFile(path.join(output, 'hero-garden-plate-v2.webp'));
}

async function run(args) {
  await new Promise((resolve, reject) => {
    const child = spawn(
      ffmpeg,
      ['-hide_banner', '-loglevel', 'warning', '-y', ...args],
      { cwd: root, stdio: 'inherit' },
    );
    child.once('error', reject);
    child.once('exit', (code) =>
      code === 0 ? resolve() : reject(new Error(`FFmpeg: ${code}`)),
    );
  });
}

// First 30 seconds stop before the price modal. Blend the end into the
// beginning, then remove the duplicated opening to produce a 12-second loop.
// Screen coordinates are measured against the 1672x941 generated source.
const cameraFilter = `zoompan=z='1.015-0.015*cos(2*PI*on/${duration * fps})':x='(iw-iw/zoom)*0.58':y='(ih-ih/zoom)*0.55':d=1:s=1280x720:fps=${fps},format=yuv420p[out]`;
const filter = matched
  ? [
      '[0:v]scale=1672:942,crop=1672:940:0:0,setsar=1[scene]',
      '[2:v]scale=640:600:force_original_aspect_ratio=decrease,format=rgba[product]',
      '[scene][product]overlay=x=970:y=165[with-product]',
      '[1:v]fps=25,scale=576:338:force_original_aspect_ratio=decrease,pad=576:338:(ow-iw)/2:(oh-ih)/2:color=171819,eq=brightness=-0.025:saturation=0.92[screen]',
      '[with-product][screen]overlay=x=156:y=311:shortest=1,' + cameraFilter,
    ].join(';')
  : [
      '[0:v]scale=1672:942,crop=1672:940:0:0,setsar=1[scene]',
      '[1:v]trim=start=0:end=30,setpts=(PTS-STARTPTS)*0.44,fps=25,settb=AVTB,split=2[main][opening]',
      '[opening]trim=duration=1.2,setpts=PTS-STARTPTS[head]',
      '[main][head]xfade=transition=fade:duration=1.2:offset=12,trim=start=1.2:duration=12,setpts=PTS-STARTPTS,' +
        'scale=576:338:force_original_aspect_ratio=decrease,pad=576:338:(ow-iw)/2:(oh-ih)/2:color=171819,eq=brightness=-0.025:saturation=0.92[screen]',
      '[scene][screen]overlay=x=156:y=311:shortest=1,' + cameraFilter,
    ].join(';');

await run([
  '-loop',
  '1',
  '-framerate',
  String(fps),
  '-i',
  path.join(
    output,
    matched ? 'hero-garden-plate-v2.webp' : 'hero-garden-scene-v1.webp',
  ),
  ...(matched
    ? [
        '-i',
        path.join(matchedSource, 'configurator.mp4'),
        '-loop',
        '1',
        '-framerate',
        String(fps),
        '-i',
        path.join(matchedSource, 'product.png'),
      ]
    : ['-i', path.join(output, 'configurator-hero.mp4')]),
  '-filter_complex',
  filter,
  '-map',
  '[out]',
  '-t',
  String(duration),
  '-an',
  '-c:v',
  'libx264',
  '-preset',
  'slow',
  '-crf',
  '21',
  '-movflags',
  '+faststart',
  path.join(output, `${name}.mp4`),
]);
await run([
  '-i',
  path.join(output, `${name}.mp4`),
  '-an',
  '-c:v',
  'libvpx-vp9',
  '-crf',
  '33',
  '-b:v',
  '0',
  '-row-mt',
  '1',
  path.join(output, `${name}.webm`),
]);
await run([
  '-ss',
  '4',
  '-i',
  path.join(output, `${name}.mp4`),
  '-frames:v',
  '1',
  '-c:v',
  'libwebp',
  '-quality',
  '86',
  path.join(output, `${name}-poster.webp`),
]);
console.log(`Created public/videos/${name}.{mp4,webm} and poster`);
